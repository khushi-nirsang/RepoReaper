package protect

import (
	"context"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"

	contentx "github.com/khushi/reporeaper/internal/content"
	"github.com/khushi/reporeaper/internal/detector"
	"github.com/khushi/reporeaper/internal/gitrepo"
	"github.com/khushi/reporeaper/internal/model"
)

const managedHook = "#!/bin/sh\n# Managed by RepoReaper. Do not edit this file in place.\nreporeaper protect staged\n"

type StagedResult struct {
	Findings []model.Finding
	Warnings []string
}

func HookPath(ctx context.Context, repoPath string) (string, error) {
	r, err := gitrepo.Open(ctx, repoPath)
	if err != nil {
		return "", err
	}
	return r.HookPath(ctx, "pre-commit")
}
func Install(ctx context.Context, repoPath string, force bool) error {
	p, err := HookPath(ctx, repoPath)
	if err != nil {
		return err
	}
	if existing, readErr := os.ReadFile(p); readErr == nil {
		if string(existing) != managedHook {
			return fmt.Errorf("pre-commit hook already exists and is not RepoReaper-managed; refusing to overwrite it")
		}
		if !force {
			return fmt.Errorf("RepoReaper pre-commit hook is already installed; use --force only to repair the managed hook")
		}
	} else if !os.IsNotExist(readErr) {
		return readErr
	}
	if err := os.MkdirAll(filepath.Dir(p), 0700); err != nil {
		return err
	}
	return os.WriteFile(p, []byte(managedHook), 0700)
}
func Uninstall(ctx context.Context, repoPath string) error {
	p, err := HookPath(ctx, repoPath)
	if err != nil {
		return err
	}
	b, err := os.ReadFile(p)
	if err != nil {
		return err
	}
	if string(b) != managedHook {
		return fmt.Errorf("existing hook was not installed by RepoReaper; refusing to remove it")
	}
	return os.Remove(p)
}
func Status(ctx context.Context, repoPath string) (string, error) {
	p, err := HookPath(ctx, repoPath)
	if err != nil {
		return "", err
	}
	b, err := os.ReadFile(p)
	if os.IsNotExist(err) {
		return "not installed", nil
	}
	if err != nil {
		return "", fmt.Errorf("inspect pre-commit hook: %w", err)
	}
	if string(b) == managedHook {
		return "installed", nil
	}
	return "occupied by another hook", nil
}
func Staged(ctx context.Context, repoPath string, detectors []detector.Detector, max int64) ([]model.Finding, error) {
	result, err := ScanStaged(ctx, repoPath, detectors, max)
	return result.Findings, err
}

// ScanStaged returns both redacted findings and non-secret coverage warnings.
// Callers enforcing a commit policy can fail closed when Warnings is non-empty.
func ScanStaged(ctx context.Context, repoPath string, detectors []detector.Detector, max int64) (StagedResult, error) {
	r, err := gitrepo.Open(ctx, repoPath)
	if err != nil {
		return StagedResult{}, err
	}
	blobs, err := r.StagedBlobs(ctx)
	if err != nil {
		return StagedResult{}, err
	}
	if len(blobs) == 0 {
		return StagedResult{}, nil
	}
	reader, err := r.NewBatchBlobReader(ctx)
	if err != nil {
		return StagedResult{}, err
	}
	defer reader.Close()
	result := StagedResult{}
	var proofs []detector.Match
	warnings := map[string]bool{}
	warn := func(message string) { warnings[message] = true }
	for _, blob := range blobs {
		body, readErr := reader.ReadBlob(blob.OID, max)
		if readErr != nil {
			if errors.Is(readErr, gitrepo.ErrObjectTooLarge) {
				warn("one or more staged files exceeded the configured size limit")
				continue
			}
			if errors.Is(readErr, gitrepo.ErrObjectMissing) {
				warn("one or more staged Git objects were unavailable")
				continue
			}
			return StagedResult{}, readErr
		}
		expanded := contentx.Expand(body, contentx.Limits{MaxUnitSize: max})
		var blobMatches []detector.Match
		for _, unit := range expanded.Units {
			path := filepath.ToSlash(blob.Path)
			if unit.Location != "" {
				path += "!" + unit.Location
			}
			prepared := detector.PrepareText(unit.Data)
			for _, d := range detectors {
				for _, match := range detector.FindPrepared(d, prepared) {
					if match.Location == "" {
						match.Location = path
					} else {
						match.Location = path + "!" + match.Location
					}
					if unit.Decoder == "" {
						// Preserve detector-provided provenance for structured formats.
					} else if match.Decoder == "" {
						match.Decoder = unit.Decoder
					} else {
						match.Decoder = unit.Decoder + "+" + match.Decoder
					}
					if unit.SourceLine > 0 {
						match.Line = unit.SourceLine
					}
					blobMatches = append(blobMatches, match)
				}
			}
		}
		blobMatches, scrubber, _ := detector.SanitizeMatches(blobMatches)
		proofs = append(proofs, blobMatches...)
		for _, warning := range expanded.Warnings {
			if sanitizedWarning := scrubber.Scrub(warning); sanitizedWarning != "" {
				warn(sanitizedWarning)
			}
		}
		for _, match := range blobMatches {
			var matchedDetector detector.Detector
			for _, candidate := range detectors {
				if candidate.ID() == match.DetectorID {
					matchedDetector = candidate
					break
				}
			}
			if matchedDetector == nil {
				continue
			}
			remediation := matchedDetector.Remediation()
			for index := range remediation {
				remediation[index] = scrubber.Scrub(remediation[index])
			}
			result.Findings = append(result.Findings, model.Finding{
				DetectorID:       scrubber.Scrub(matchedDetector.ID()),
				DetectorName:     scrubber.Scrub(matchedDetector.Name()),
				Category:         scrubber.Scrub(matchedDetector.Category()),
				Severity:         matchedDetector.Severity(),
				Confidence:       match.Confidence,
				Fingerprint:      match.Fingerprint,
				ShortFingerprint: match.Short,
				Redacted:         match.Redacted,
				Evidence:         []model.Evidence{{Source: "index", Path: match.Location, Line: match.Line, Blob: scrubber.Scrub(blob.OID), Decoder: match.Decoder}},
				Paths:            []string{match.Location},
				Remediation:      remediation,
			})
		}
		if err := ctx.Err(); err != nil {
			return StagedResult{}, err
		}
	}
	if err := reader.Close(); err != nil {
		return StagedResult{}, err
	}
	for warning := range warnings {
		result.Warnings = append(result.Warnings, warning)
	}
	sort.Strings(result.Warnings)
	globalScrubber, _ := detector.NewCaptureScrubber(proofs)
	scrubStagedResult(&result, globalScrubber)
	return result, nil
}

func scrubStagedResult(result *StagedResult, scrubber detector.CaptureScrubber) {
	for index := range result.Findings {
		scrubStagedFinding(&result.Findings[index], scrubber)
	}
	for index := range result.Warnings {
		result.Warnings[index] = scrubber.Scrub(result.Warnings[index])
	}
}

func scrubStagedFinding(finding *model.Finding, scrubber detector.CaptureScrubber) {
	finding.ID = scrubber.Scrub(finding.ID)
	finding.DetectorID = scrubber.Scrub(finding.DetectorID)
	finding.DetectorName = scrubber.Scrub(finding.DetectorName)
	finding.Category = scrubber.Scrub(finding.Category)
	finding.ConfidenceReason = scrubber.Scrub(finding.ConfidenceReason)
	finding.RiskExplanation = scrubber.Scrub(finding.RiskExplanation)
	finding.Redacted = scrubber.Scrub(finding.Redacted)
	finding.CurrentStatus = scrubber.Scrub(finding.CurrentStatus)
	finding.RemoteStatus = scrubber.Scrub(finding.RemoteStatus)
	finding.RemoteReason = scrubber.Scrub(finding.RemoteReason)
	scrubStagedEvidence(finding.FirstSeen, scrubber)
	scrubStagedEvidence(finding.LastSeen, scrubber)
	scrubStagedEvidence(finding.Introduced, scrubber)
	scrubStagedEvidence(finding.Removed, scrubber)
	for index := range finding.ExposureIntervals {
		finding.ExposureIntervals[index].StartCommit = scrubber.Scrub(finding.ExposureIntervals[index].StartCommit)
		finding.ExposureIntervals[index].EndCommit = scrubber.Scrub(finding.ExposureIntervals[index].EndCommit)
		finding.ExposureIntervals[index].RemovedBy = scrubber.Scrub(finding.ExposureIntervals[index].RemovedBy)
		finding.ExposureIntervals[index].Status = scrubber.Scrub(finding.ExposureIntervals[index].Status)
	}
	for index := range finding.Evidence {
		scrubStagedEvidence(&finding.Evidence[index], scrubber)
	}
	scrubStagedStrings(finding.Paths, scrubber)
	scrubStagedStrings(finding.Branches, scrubber)
	scrubStagedStrings(finding.Tags, scrubber)
	scrubStagedStrings(finding.Remediation, scrubber)
}

func scrubStagedEvidence(evidence *model.Evidence, scrubber detector.CaptureScrubber) {
	if evidence == nil {
		return
	}
	evidence.Source = scrubber.Scrub(evidence.Source)
	evidence.Commit = scrubber.Scrub(evidence.Commit)
	evidence.Blob = scrubber.Scrub(evidence.Blob)
	evidence.Path = scrubber.Scrub(evidence.Path)
	evidence.Ref = scrubber.Scrub(evidence.Ref)
	evidence.AuthorName = scrubber.Scrub(evidence.AuthorName)
	evidence.AuthorEmail = scrubber.Scrub(evidence.AuthorEmail)
	evidence.Decoder = scrubber.Scrub(evidence.Decoder)
}

func scrubStagedStrings(values []string, scrubber detector.CaptureScrubber) {
	for index := range values {
		values[index] = scrubber.Scrub(values[index])
	}
}
